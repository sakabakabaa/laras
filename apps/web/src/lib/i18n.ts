/**
 * Interface language for an account. Lecturers choose their own on the settings
 * page; lecturers also choose each enrolled student's dashboard language from
 * the roster page. Students default to German; other accounts default to Indonesian.
 */
export type Language = 'id' | 'en' | 'de';

export const DEFAULT_LANGUAGE: Language = 'id';
export const DEFAULT_STUDENT_LANGUAGE: Language = 'de';

export const LANGUAGES: { code: Language; native: string; english: string }[] = [
	{ code: 'id', native: 'Bahasa Indonesia', english: 'Indonesian' },
	{ code: 'en', native: 'English', english: 'English' },
	{ code: 'de', native: 'Deutsch', english: 'German' },
];

export function isLanguage(value: unknown): value is Language {
	return value === 'id' || value === 'en' || value === 'de';
}

export function languageOf(user: Record<string, unknown> | null | undefined): Language {
	const language = user?.language;
	if (isLanguage(language)) return language;
	return user?.role === 'student' ? DEFAULT_STUDENT_LANGUAGE : DEFAULT_LANGUAGE;
}

export function nativeName(code: string): string {
	return LANGUAGES.find((l) => l.code === code)?.native ?? code;
}

