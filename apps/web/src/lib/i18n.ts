const DICTS: Record<Language, Dict> = { id, en, de };

/** Translate a key in the given language, interpolating `{var}` placeholders. */
export function translate(lang: Language, key: string, vars?: Record<string, string>): string {
	const dict = DICTS[lang] ?? DICTS[DEFAULT_LANGUAGE];
	let s = dict[key] ?? DICTS[DEFAULT_LANGUAGE][key] ?? key;
	if (vars) {
		for (const k of Object.keys(vars)) {
			s = s.replaceAll(`{${k}}`, vars[k]);
		}
	}
	return s;
}

/** Reactive interface language of the signed-in user. */
export function useLanguage(): Language {
	const [lang, setLang] = useState<Language>(() => languageOf(pb.authStore.record));
	useEffect(() => {
		setLang(languageOf(pb.authStore.record));
		return pb.authStore.onChange(() => setLang(languageOf(pb.authStore.record)));
	}, []);
	return lang;
}

/** Translation function bound to the signed-in user's language. */
export function useT() {
	const lang = useLanguage();
	return useCallback(
		(key: string, vars?: Record<string, string>) => translate(lang, key, vars),
		[lang],
	);
}
